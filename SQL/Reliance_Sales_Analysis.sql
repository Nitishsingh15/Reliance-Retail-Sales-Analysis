--  highest revenue product in each category using DENSE_RANK().
with cte as (
select p.Category ,p.Product_Name, round(sum(o.Quantity * p.Selling_Price),2) as Revenue
from products p join orders o on o.Product_ID = p.Product_ID 
group by p.Category ,p.Product_Name) ,
high_rev as (
select * , 
dense_rank()over(partition by Category order by Revenue desc ) as rnk from  cte ) 
select * from high_rev where rnk =1;

-- Rank stores within each city based on revenue.
with cte as (
select s.Store_ID, s.Store_Name ,s.City, round(sum(o.Quantity * p.Selling_Price),2) as Revenue 
from stores s join orders o  on s.Store_ID = o.Store_ID
join products p on p.Product_ID=o.Product_ID 
group by s.Store_ID, s.Store_Name , s.City) 
select * , rank() over(partition by city order by Revenue desc) as rnk from cte;

-- Top 3 products in each category based on total revenue.  and classify each product as 'High Performer', 'Average Performer', or 'Low Performer' using CASE.

 
WITH cte AS (
SELECT p.Category, p.Product_ID, p.Product_Name,
ROUND(SUM(o.Quantity * p.Selling_Price), 2) AS Revenue
FROM products p
JOIN orders o ON p.Product_ID = o.Product_ID
GROUP BY p.Category, p.Product_ID, p.Product_Name
),
classify AS (SELECT *,
RANK() OVER(PARTITION BY Category ORDER BY Revenue DESC) AS rnk
FROM cte
),
top3 AS (SELECT *,
CASE
WHEN Revenue >= 120000 THEN 'High Performer'
WHEN Revenue >= 50000 THEN 'Average Performer'
ELSE 'Low Performer'
END AS Product_Status
FROM classify
)
SELECT * FROM top3 WHERE rnk <=3;


