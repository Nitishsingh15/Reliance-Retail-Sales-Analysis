-- total revenue, total orders, and AOV.
with cte as (
select round(sum(o.Quantity * p.Selling_Price),2)as Total_Revenue , count(o.Order_ID) as Total_Orders
from orders o join products p on p.Product_ID=o.Product_ID)
select * , 
round((Total_Revenue / Total_Orders),2) as AOV from cte;

-- top 10 products based on total quantity sold.
select p.Product_ID,p.Product_Name,sum(o.Quantity) as Total_Quantity from Products p 
join orders o on p.Product_ID=o.Product_ID 
group by p.Product_ID,p.Product_Name 
order by Total_Quantity desc limit 10;

-- total revenue generated by each payment mode.
select o.Payment_Mode , round(sum(o.Quantity * p.Selling_Price),2) as Total_Revenue 
from orders o join products p on p.Product_ID=o.Product_ID 
group by  o.Payment_Mode ;


--  top 10 stores with the highest revenue.
select s.Store_ID,s.Store_Name,s.City,round(sum(o.Quantity * p.Selling_Price),2) as Total_Revenue 
from stores s join orders o on s.Store_ID = o.Store_ID 
join products p on p.Product_ID = o.Product_ID 
group by s.Store_ID,s.Store_Name,s.City 
order by Total_Revenue  desc limit 10;


-- categories whose total revenue is greater than 500000.
select p.Category , round(sum(o.Quantity * p.Selling_Price),2) as Total_Revenue 
from products p join orders o on p.Product_ID = o.Product_ID 
group by  p.Category  
having Total_Revenue > 500000;

-- top 15 customers based on total spending.--
